#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""install_git_hook.py — 一键安装 Git Pre-Commit / Pre-Push 隐私与防反向泄密拦截钩子。

功能定位：
  在目标 Git 仓库的 `.git/hooks/` 下部署自动化拦截钩子。
  在执行 `git commit` 或 `git push` 前，自动触发 `audit_privacy_leak.py --strict`。
  若检测到任何 CRITICAL 或 HIGH 级别的凭据、作者个人路径、开发环境指纹、
  私有课程体系标识、或内部负向清单约束文件（反向泄密），立即阻断并退出（exit 1），
  彻底杜绝手滑将敏感信息或内部约束推送到公开开源仓库！
"""

from __future__ import annotations

import argparse
import os
import pathlib
import stat
import sys

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
if hasattr(sys.stderr, "reconfigure"):
    sys.stderr.reconfigure(encoding="utf-8", errors="replace")

HOOK_TEMPLATE = """#!/bin/sh
# Auto-generated by opensource-privacy-audit skill
echo "[*] [Hook: {hook_type}] 启动开源隐私、凭据与防反向泄密拦截审计..."

# 确定 Python 解释器
if command -v python3 >/dev/null 2>&1; then
    PY="python3"
elif command -v python >/dev/null 2>&1; then
    PY="python"
elif command -v py >/dev/null 2>&1; then
    PY="py"
else
    echo "❌ [安全阻断] 未检测到 Python 解释器，无法执行隐私安全门禁！"
    exit 1
fi

# 优先查找仓库自身的 scripts/audit_privacy_leak.py，其次使用全局 Skill 路径
SCRIPT_PATH="scripts/audit_privacy_leak.py"
if [ ! -f "$SCRIPT_PATH" ]; then
    SCRIPT_PATH="{fallback_script_path}"
fi

if [ ! -f "$SCRIPT_PATH" ]; then
    echo "❌ [安全阻断] 未找到 audit_privacy_leak.py 脚本！"
    exit 1
fi

if [ "{hook_type}" = "pre-push" ]; then
    $PY "$SCRIPT_PATH" --target "." --strict --audit-history
else
    $PY "$SCRIPT_PATH" --target "." --strict
fi
RET=$?

if [ $RET -ne 0 ]; then
    echo ""
    echo "❌ [安全阻断] 检测到敏感凭据、作者隐私、开发环境指纹或内部约束反向泄密！"
    echo "   已阻断 {hook_type} 流程，严禁提交或推送到开源仓库。"
    echo "   请根据上述输出清单完成脱敏修复后再试。"
    exit 1
fi

echo "✅ [安全通过] 隐私、凭据与防反向泄密审计全部合规，允许继续。"
exit 0
"""


def install_hook(repo_dir: pathlib.Path, hook_type: str = "pre-commit", force: bool = True) -> bool:
    repo_dir = repo_dir.resolve()
    git_dir = repo_dir / ".git"
    if not git_dir.is_dir():
        print(f"❌ 错误: {repo_dir} 不是一个合法的 Git 仓库（未找到 .git 目录）")
        return False

    hooks_dir = git_dir / "hooks"
    hooks_dir.mkdir(parents=True, exist_ok=True)
    target_hook = hooks_dir / hook_type

    # 计算 fallback 脚本路径（若当前环境有安装 Skill，记录其绝对路径）
    skill_script = pathlib.Path(__file__).resolve().parent / "audit_privacy_leak.py"
    fallback_script_str = skill_script.as_posix()

    content = HOOK_TEMPLATE.format(
        hook_type=hook_type,
        fallback_script_path=fallback_script_str,
    )
    target_hook.write_text(content, encoding="utf-8")

    # 赋予执行权限（针对 Unix/Git Bash）
    try:
        st = os.stat(target_hook)
        os.chmod(target_hook, st.st_mode | stat.S_IEXEC | stat.S_IXGRP | stat.S_IXOTH)
    except Exception:
        pass

    print(f"✅ 成功安装 {hook_type} 钩子至: {target_hook}")
    return True


def remove_hook(repo_dir: pathlib.Path, hook_type: str) -> bool:
    repo_dir = repo_dir.resolve()
    target_hook = repo_dir / ".git" / "hooks" / hook_type
    if target_hook.exists():
        target_hook.unlink()
        print(f"🗑️ 已卸载 {hook_type} 钩子: {target_hook}")
        return True
    return False


def main():
    parser = argparse.ArgumentParser(description="Git 隐私与防反向泄密安全拦截钩子安装工具")
    parser.add_argument("--repo", "-r", default=".", help="目标 Git 仓库根目录")
    parser.add_argument("--hook-type", choices=["pre-commit", "pre-push", "both"], default="both", help="安装的钩子类型（默认 both）")
    parser.add_argument("--remove", action="store_true", help="卸载/移除指定的钩子")
    args = parser.parse_args()

    repo_path = pathlib.Path(args.repo).resolve()
    target_hooks = ["pre-commit", "pre-push"] if args.hook_type == "both" else [args.hook_type]

    for ht in target_hooks:
        if args.remove:
            remove_hook(repo_path, ht)
        else:
            install_hook(repo_path, ht)


if __name__ == "__main__":
    main()
